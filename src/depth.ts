  const visible = list(wealth.filter((r) => r.layer === 'visible').map(describe));
  const hidden = list(wealth.filter((r) => r.layer !== 'visible').map(describe));
  const direct = STEMS.find((s) => tenGod(chart.dayMaster, s).name === '正财')!;
  const indirect = STEMS.find((s) => tenGod(chart.dayMaster, s).name === '偏财')!;
