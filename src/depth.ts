export function buildDepth(
  chart: Chart,
  report: ReturnType<typeof buildStructureReading>,
  facts: RoleFact[],
  context: EverydayContext,
): Record<string, DepthSection[]> {
  const f = report.features,
    annual = report.annual;
  const selected = (groups: number[], salient = false) =>
    facts.filter(
      (r) =>
        groups.some((g) => families[g].includes(r.god)) &&
        (!salient || r.layer === 'visible' || (r.position === 1 && r.layer === 'main')),
    );
  const roots = list(
    f.roots.map((r) =>
      w(
        `${pos[r.position]}支${r.branch}藏${r.stem}（${r.main ? '本气' : '余气/中气'}）`,
        `${posEn[r.position]} branch ${r.branch} contains ${r.stem} (${r.main ? 'main' : 'additional'} qi)`,
      ),
    ),
  );
  const strength = {
    supported: w(
      '本版的简化筛查发现季节、根与显干支持同时出现，因此保留“支持线索较齐”的读法；这不是已经定了身旺格。',
      'Our limited screen finds aligned seasonal, root and visible-stem support; this does not establish a formal strong pattern.',
    ),
    drained: w(
      '本版的简化筛查没有找到同类根，月令也不直接帮扶，因此先关注“承接条件是否不足”；不据此认定人软弱或做不成事。',
      'Our limited screen finds no same-phase roots and no direct seasonal support, so symbolic support remains a question. This says nothing about courage or real ability.',
    ),
    mixed: w(
      '支持与消耗线索并不单一，本版保留两面，不把它硬定为身强或身弱，也不把“混合”当成恰好平衡。',
      'Support and drain are mixed. We retain both possibilities rather than declare strength, weakness or perfect balance.',
    ),
    withheld: w(
      `本盘${!f.complete ? '缺少时柱' : f.concentrated ? '五行较集中' : '月支本气属土'}，超出这套简化筛查适合判断的范围，因此暂不定身强身弱。`,
      `This chart ${!f.complete ? 'has no hour pillar' : f.concentrated ? 'has concentrated phases' : 'has Earth as main month qi'}, so our limited strength screen withholds judgment.`,
    ),
  }[f.strength];
  const rootBasis = w(
    `同类根：${roots.zh}。年、月、时显干中，帮扶线索${f.support.length}处，输出、财或官杀线索${f.drain.length}处；这里只列位置，不按个数直接比强弱。${!f.complete ? '时柱未知，未列出的信息不算不存在。' : ''}`,
    `Same-phase roots: ${roots.en}. Visible non-day stems: ${f.support.length} supportive and ${f.drain.length} output/wealth/authority positions. These are positions, not strength weights.${!f.complete ? ' The hour is unknown, not absent from life.' : ''}`,
  );
  const work = workDetails[context.career];
  const overview = [
    section(
      w(
        '日主与月令：先确定“从谁的角度、在什么背景下看”',
        'Day stem and month: reference and setting',
      ),
      [
        w(
          `日主是日柱天干，本盘为${chart.dayMaster}${f.day}，相当于整张关系图的观察中心；它不是“你只属于一种五行”。月令是出生月的地支，提供节气背景。本盘月支为${chart.pillars[1].branch}，本气${f.monthMain.stem}，对日主是${f.monthMain.god}。所以开头先谈${family[f.monthRelation]}主题，而不是随便抽一句性格评语。`,
          `The day stem ${chart.dayMaster} (${f.day}) is the reference for this relationship map, not a claim that a person consists of one phase. The month branch ${chart.pillars[1].branch}, with main qi ${f.monthMain.stem} (${f.monthMain.god}), supplies the seasonal starting point.`,
        ),
        w(
          '这句古文里的“用神”以月令立论，接着讨论怎样配合日干、辨别格局。它与日常说的“找一种能补我的五行”并非同一个简化问题。因此看到缺某个字，就建议补某种颜色或物品，跳过了原文的判断过程。',
          'In this passage, yong shen begins with the month and its relationship to the day stem and pattern. It is not simply a missing phase to repair with a color or object.',
        ),
      ],
      undefined,
      'month',
    ),
    section(
      w('通根与透干：有字出现，还要看有没有落脚处', 'Roots and exposure: presence and grounding'),
      [
        w(
          '地支里还藏着天干，叫“藏干”。其中与日主同五行的线索叫“通根”，可把它想成树有地下的根；藏着的某个天干又在年、月、时天干出现，本版会标出“透干”。一个关注有没有根基，一个关注同一线索是否显露，不能把两个名字混为一谈。',
          'Branches contain hidden stems. Same-phase hidden stems are recorded as roots, like a tree’s grounding. When an exact hidden stem also appears in a visible non-day stem, the app records exposure. Grounding and exposure answer different questions.',
        ),
        w(
          '“干多不如根重”提醒读者，数出几个木、几个金还不够；位置、本气或其他藏气、季节都影响传统读法。本版把这些依据列出，但尚未计算根在合冲后的变化。',
          'The short excerpt stresses that visible counts alone are insufficient; position, main or additional qi and season matter. This app lists those facts without resolving changes to roots after combinations or clashes.',
        ),
      ],
      w(
        `${rootBasis.zh} 同字透干：${list(f.exposed.map((x) => w(`${pos[x.position]}支${x.branch}中的${x.stem}`, `${x.stem} from ${posEn[x.position]} branch ${x.branch}`))).zh}。`,
        `${rootBasis.en} Exact-stem exposure: ${list(f.exposed.map((x) => w('', `${x.stem} from ${posEn[x.position]} branch ${x.branch}`))).en}.`,
      ),
      'roots',
    ),
    section(
      w(
        '身强身弱：说的是关系承接，不是人的高低',
        'Strength: a symbolic condition, not personal worth',
      ),
      [
        strength,
        w(
          '把命盘比作一张工作台：“支持”像支架，“输出、财、官杀”像台面上不同的任务。判断关心的是这套配置怎样配合，不是任务越少越好，也不是支架越多越好。这个比喻只是帮助理解；你的执行力、性格和身体状况，不能靠这里的强弱标签测出来。',
          'As an explanatory metaphor, support resembles a workbench frame and output, wealth and authority resemble different tasks on it. The question is how the arrangement fits together, not whether more support is always better. This metaphor does not measure personality, ability or health.',
        ),
      ],
    ),
  ];
  const workSections = [
    section(
      work.title,
      [work.meaning, work.scene],
      list(selected(work.groups, true).map(describe)),
      work.source,
    ),
    section(
      w('这条线索能走多远，还要看根与承接', 'What supports this theme?'),
      [work.condition, strength],
      rootBasis,
    ),
  ];

  return { overview, work: workSections, ...otherDepth(chart, report, facts, context, strength) };
}

